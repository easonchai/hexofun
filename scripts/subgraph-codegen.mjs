#!/usr/bin/env node
// Writes subgraph/src/generated.rs from the program IDL: each event's
// discriminator and borsh field layout, and each instruction's discriminator
// with the index of its `pool` account. Run by `scripts/subgraph.sh build`.
// Any IDL type the decoder cannot read stops the run, so a program change can
// never produce a silently wrong layout.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const idlPath = path.join(root, "apps/web/src/idl/hex_vault.json");
const outPath = path.join(root, "subgraph/src/generated.rs");
const idl = JSON.parse(fs.readFileSync(idlPath, "utf8"));

const PRIMITIVES = { pubkey: "Pubkey", u8: "U8", u16: "U16", u32: "U32", u64: "U64", u128: "U128", i64: "I64", bool: "Bool" };

const fail = (msg) => {
  console.error(`subgraph-codegen: ${msg}`);
  process.exit(1);
};

const fieldType = (event, field) => {
  const t = field.type;
  if (typeof t === "string" && PRIMITIVES[t]) return PRIMITIVES[t];
  const name = t?.defined?.name;
  const def = name && idl.types.find((d) => d.name === name);
  // A fieldless enum is one u8 tag on the wire (PauseFeature).
  if (def?.type.kind === "enum" && def.type.variants.every((v) => !v.fields)) return "U8";
  return fail(`${event}.${field.name}: unsupported type ${JSON.stringify(t)}`);
};

const bytes = (d) => `[${d.join(", ")}]`;

const events = idl.events.map((e) => {
  const def = idl.types.find((t) => t.name === e.name);
  if (def?.type.kind !== "struct") fail(`event ${e.name} has no struct type`);
  const fields = def.type.fields.map((f) => `("${f.name}", Ty::${fieldType(e.name, f)})`);
  return `    EventDef { name: "${e.name}", disc: ${bytes(e.discriminator)}, fields: &[${fields.join(", ")}] },`;
});

const instructions = idl.instructions.map((ix) => {
  const pool = ix.accounts.findIndex((a) => a.name === "pool");
  if (pool < 0) fail(`instruction ${ix.name} has no pool account`);
  return `    (${bytes(ix.discriminator)}, ${pool}), // ${ix.name}`;
});

const out = `// Generated by scripts/subgraph-codegen.mjs from apps/web/src/idl/hex_vault.json. Do not edit.
use crate::decode::{EventDef, Ty};

pub const EVENTS: &[EventDef] = &[
${events.join("\n")}
];

/// Instruction discriminator and the index of its \`pool\` account.
pub const POOL_ACCOUNT: &[([u8; 8], usize)] = &[
${instructions.join("\n")}
];
`;

fs.writeFileSync(outPath, out);
console.log(`subgraph-codegen: ${idl.events.length} events, ${idl.instructions.length} instructions -> ${path.relative(root, outPath)}`);
